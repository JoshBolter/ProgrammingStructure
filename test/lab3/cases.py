from dataclasses import dataclass


@dataclass(frozen=True)
class Case:
    name: str
    purpose: str
    source: str
    stdout: str = ""
    stderr: str = ""
    returncode: int = 0
    cause: str = ""
    mode: str = "file"
    stderr_pattern: bool = False


def valid(name, purpose, source, ast):
    return Case(name, purpose, source, ast + "\n")


def invalid(name, purpose, source, line, column, message, cause):
    return Case(
        name, purpose, source,
        stderr=f"[line {line}, column {column}] Syntax error: {message}\n",
        returncode=65, cause=cause,
    )


